<?php

declare(strict_types=1);

namespace App\Entity;

use App\Entity\Trait\TimestampableTrait;
use App\Entity\Trait\UuidIdTrait;
use App\Enum\ZoneType;
use App\Repository\RegionRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Component\Uid\Uuid;
use Symfony\Component\Validator\Constraints as Assert;

#[ORM\Entity(repositoryClass: RegionRepository::class)]
#[ORM\Index(name: 'region_boundary_gist', fields: ['boundary'], flags: ['spatial'])]
#[ORM\Index(name: 'region_centroid_gist', fields: ['centroid'], flags: ['spatial'])]
class Region implements ZoneInterface
{
    use TimestampableTrait;
    use UuidIdTrait;

    // The zone's natural key — treated as immutable identity, not a
    // mutable attribute (see UuidIdTrait's id for the same reasoning).
    #[ORM\Column(length: 3, unique: true)]
    #[Assert\NotBlank]
    #[Assert\Regex('/^[0-9A-Z]{2,3}$/', message: 'The INSEE region code must be 2 or 3 alphanumeric characters.')]
    private readonly string $inseeCode;

    #[ORM\Column(length: 255)]
    #[Assert\NotBlank]
    private string $name;

    /** EWKT (e.g. "SRID=4326;MULTIPOLYGON(...)"), see ZoneInterface::getBoundary(). */
    #[ORM\Column(type: 'geometry', nullable: true, options: ['geometry_type' => 'MULTIPOLYGON', 'srid' => 4326])]
    private ?string $boundary = null;

    /**
     * Generated by Postgres (`GENERATED ALWAYS AS (ST_Centroid(boundary)) STORED`,
     * added by hand in the migration), used for the zone↔POI nearest-neighbor
     * distance query. Read-only from Doctrine's point of view.
     *
     * The `default` option below isn't a real default (Doctrine has no
     * concept of a generated/computed column) — it's set to exactly match
     * what Postgres reports back for this column (`pg_get_expr`) so that
     * `doctrine:schema:validate`/`schema:update` stop proposing a spurious
     * `ALTER ... DROP DEFAULT`. This only works because jsor/doctrine-postgis
     * hardcodes its DBAL platform to plain `PostgreSQLPlatform` instead of
     * version-aware `PostgreSQL120Platform`, so it misses upstream DBAL's
     * own generated-column handling (`PostgreSQL120Platform::getDefaultColumnValueSQLSnippet()`,
     * which nulls this out).
     *
     * The GiST index on this column (and on `boundary`) is declared via the
     * class-level `#[ORM\Index(..., flags: ['spatial'])]` attributes above
     * — jsor/doctrine-postgis natively supports that flag end to end
     * (`Jsor\Doctrine\PostGIS\Driver\PostGISPlatform::getCreateIndexSQL()`
     * emits `USING gist(...)`, and its `SchemaManager::listTableIndexes()`
     * auto-flags any introspected index on a geometry/geography column as
     * `spatial`), so it round-trips cleanly with `schema:validate` too.
     */
    #[ORM\Column(type: 'geography', nullable: true, insertable: false, updatable: false, options: ['geometry_type' => 'POINT', 'srid' => 4326, 'default' => '(st_centroid(boundary))::geography'])]
    private ?string $centroid = null;

    /** @var Collection<int, Departement> */
    #[ORM\OneToMany(targetEntity: Departement::class, mappedBy: 'region')]
    private Collection $departements;

    public function __construct(string $inseeCode, string $name)
    {
        $this->id = Uuid::v7();
        $this->createdAt = new \DateTimeImmutable();
        $this->updatedAt = $this->createdAt;
        $this->inseeCode = $inseeCode;
        $this->name = $name;
        $this->departements = new ArrayCollection();
    }

    public function getCode(): string
    {
        return $this->inseeCode;
    }

    public function getInseeCode(): string
    {
        return $this->inseeCode;
    }

    public function getName(): string
    {
        return $this->name;
    }

    public function setName(string $name): static
    {
        $this->name = $name;

        return $this;
    }

    public function getBoundary(): ?string
    {
        return $this->boundary;
    }

    public function setBoundary(?string $boundary): static
    {
        $this->boundary = $boundary;

        return $this;
    }

    public function getCentroid(): ?string
    {
        return $this->centroid;
    }

    public function getType(): ZoneType
    {
        return ZoneType::Region;
    }

    /** @return Collection<int, Departement> */
    public function getDepartements(): Collection
    {
        return $this->departements;
    }
}
